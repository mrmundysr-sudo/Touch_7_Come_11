#!/usr/bin/env python3
"""Run after `npx cap add android`: locks portrait, sets the dark theme + fullscreen, installs the app icons."""
import re
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
AND = ROOT / "android" / "app" / "src" / "main"

# --- manifest: portrait only
mf = AND / "AndroidManifest.xml"
s = mf.read_text()
if "screenOrientation" not in s:
    s = s.replace("<activity", '<activity\n            android:screenOrientation="portrait"', 1)
mf.write_text(s)

# --- dark window + status bar colours
colors = AND / "res" / "values" / "colors.xml"
colors.write_text('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="t7_night">#0B0A1C</color>\n</resources>\n')
styles = AND / "res" / "values" / "styles.xml"
if styles.exists():
    st = styles.read_text()
    st = re.sub(r"(<style name=\"AppTheme.NoActionBar\"[^>]*>)", r'\1\n        <item name="android:windowBackground">@color/t7_night</item>\n        <item name="android:statusBarColor">@color/t7_night</item>\n        <item name="android:navigationBarColor">@color/t7_night</item>', st, count=1)
    styles.write_text(st)

# --- icons (tools/icons/*.png are generated by tools/prepare_art.py from the splash art)
icons = ROOT / "tools" / "icons"
full = Image.open(icons / "icon-1024.png").convert("RGBA")
fg = Image.open(icons / "icon-foreground-1024.png").convert("RGBA")
bg = Image.open(icons / "icon-background-1024.png").convert("RGBA")
legacy = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
adaptive = {"mdpi": 108, "hdpi": 162, "xhdpi": 216, "xxhdpi": 324, "xxxhdpi": 432}
for d, px in legacy.items():
    out = AND / "res" / f"mipmap-{d}"
    out.mkdir(parents=True, exist_ok=True)
    img = full.resize((px, px), Image.LANCZOS)
    img.save(out / "ic_launcher.png")
    img.save(out / "ic_launcher_round.png")
for d, px in adaptive.items():
    out = AND / "res" / f"mipmap-{d}"
    fg.resize((px, px), Image.LANCZOS).save(out / "ic_launcher_foreground.png")
    bg.resize((px, px), Image.LANCZOS).save(out / "ic_launcher_background.png")
# adaptive icon xml: use our background/foreground pngs
any_dir = AND / "res" / "mipmap-anydpi-v26"
any_dir.mkdir(parents=True, exist_ok=True)
xml = '<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n    <background android:drawable="@mipmap/ic_launcher_background"/>\n    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>\n</adaptive-icon>\n'
(any_dir / "ic_launcher.xml").write_text(xml)
(any_dir / "ic_launcher_round.xml").write_text(xml)
print("Android project patched.")
